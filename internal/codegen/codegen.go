func isBooleanAttribute(name string) bool {
	return booleanAttrs[strings.ToLower(name)]
}

func isVoid(name string) bool {
	switch name {
	case "area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr":
		return true
	default:
		return false
	}
}
